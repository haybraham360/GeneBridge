/**
 * Writes lib/assistant/libraryIndex.ts from the files in
 * content/library/{en,ar}/{conditions,general}. Run after adding or
 * removing a library entry:
 *
 *   npm run library:index
 *
 * `lib/assistant/library.test.ts` fails when the index is out of date or an
 * entry exists in one language only.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(__dirname, '..');
const locales = ['en', 'ar'] as const;
const folders = ['conditions', 'general'] as const;

export function libraryFiles(): Record<(typeof locales)[number], { folder: string; id: string }[]> {
  const out = { en: [], ar: [] } as Record<(typeof locales)[number], { folder: string; id: string }[]>;
  for (const locale of locales) {
    for (const folder of folders) {
      const dir = join(root, 'content/library', locale, folder);
      for (const file of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
        out[locale].push({ folder, id: file.replace(/\.json$/, '') });
      }
    }
  }
  return out;
}

export function renderIndex(): string {
  const files = libraryFiles();
  const name = (locale: string, id: string) => `${locale}_${id}`;
  const lines = [
    '// Generated by scripts/gen-library-index.ts (npm run library:index). Do not edit by hand.',
    '// Add a library entry by adding its JSON file in both content/library/en and content/library/ar.',
  ];
  for (const locale of locales) {
    for (const { folder, id } of files[locale]) {
      lines.push(`import ${name(locale, id)} from '@/content/library/${locale}/${folder}/${id}.json';`);
    }
  }
  lines.push('', 'export const rawEntries = {');
  for (const locale of locales) {
    lines.push(`  ${locale}: [`);
    for (const { id } of files[locale]) lines.push(`    ${name(locale, id)},`);
    lines.push('  ],');
  }
  lines.push('} as const;', '');
  return lines.join('\n');
}

if (require.main === module) {
  writeFileSync(join(root, 'lib/assistant/libraryIndex.ts'), renderIndex());
  const files = libraryFiles();
  console.log(`libraryIndex.ts: ${files.en.length} en, ${files.ar.length} ar entries`);
}
